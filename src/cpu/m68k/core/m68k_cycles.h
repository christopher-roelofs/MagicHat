/*
 * m68k_cycles.h -- retained legacy instruction cycle table.
 *
 * Historical reference-core cycle costs, retained for Envoy elapsed-time
 * modeling. These are not verified MC68349 bus timings. The table is data;
 * it has no build-time dependency on the former reference core.
 *
 * The key is (instruction, size, source mode, destination
 * mode). What the key does not capture is handled in the
 * decoder and the interpreter as rules, because it depends on
 * an operand rather than on an encoding:
 *
 *   - a conditional branch costs more when it is taken;
 *   - a loop instruction costs more when its counter expires;
 *   - MOVEM charges four more for every register past the
 *     first, and the entry here is the one-register cost;
 *   - a shift whose count is in a register charges one per
 *     shift, and the entry here is the count-of-one cost;
 *   - an indexed address with a full extension word charges a
 *     penalty read out of the same core's own table.
 *
 * The key is m68k_cycle_key(), which both this tool and the
 * decoder use, so the two cannot drift apart.
 */
