#include "devices/magicbus/keyboard.h"
/* USB HID keyboard usage IDs (also SDL scancodes) -> AT set 2.
 * SDL_scancode.h defines the input IDs; set 2 assignments cross-checked with
 * Linux drivers/input/keyboard/atkbd.c, atkbd_set2_keycode. These are protocol
 * numbers, not host-layout characters: Magic Cap owns the resulting layout.
 * Bit 8 means E0. Pause/PrintScreen need special sequences and are excluded. */
bool mh_mb_keyboard_usage(unsigned usage, uint8_t *code, bool *extended)
{
    static const uint16_t map[256] = {
        [4]=0x1c,0x32,0x21,0x23,0x24,0x2b,0x34,0x33,0x43,0x3b,0x42,0x4b,
        0x3a,0x31,0x44,0x4d,0x15,0x2d,0x1b,0x2c,0x3c,0x2a,0x1d,0x22,0x35,0x1a,
        [30]=0x16,0x1e,0x26,0x25,0x2e,0x36,0x3d,0x3e,0x46,0x45,
        [40]=0x5a,0x76,0x66,0x0d,0x29,0x4e,0x55,0x54,0x5b,0x5d,0x5d,0x4c,
        0x52,0x0e,0x41,0x49,0x4a,0x58,
        [58]=0x05,0x06,0x04,0x0c,0x03,0x0b,0x83,0x0a,0x01,0x09,0x78,0x07,
        [71]=0x7e,
        [73]=0x170,0x16c,0x17d,0x171,0x169,0x17a,0x174,0x16b,0x172,0x175,
        [83]=0x77,0x14a,0x7c,0x7b,0x79,0x15a,0x69,0x72,0x7a,0x6b,0x73,0x74,
        0x6c,0x75,0x7d,0x70,0x71,0x61,
        [224]=0x14,0x12,0x11,0x11f,0x114,0x59,0x111,0x127
    };
    if (usage >= 256 || !map[usage]) return false;
    *code = (uint8_t)map[usage]; *extended = (map[usage] & 0x100) != 0;
    return true;
}
